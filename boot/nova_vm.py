def build_image(size_mb: int = 128) -> str:
    """Build a bootable FAT32 disk image with NOVA EFI."""
    os.makedirs(BUILD, exist_ok=True)

    # Generate BOOTX64.EFI
    from boot.efi_builder import build_efi
    efi_path = os.path.join(BUILD, "BOOTX64.EFI")
    print("  Building BOOTX64.EFI...")
    build_efi(efi_path, verify=True)
    efi_data = open(efi_path, "rb").read()
    print(f"  EFI: {len(efi_data)} bytes")

    # Collect NOVA source files
    print("  Collecting NOVA source...")
    nova_files = {}
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in ("__pycache__", ".git", "build", ".nova")]
        for fname in filenames:
            if fname.endswith((".py", ".md", ".txt", ".sh", ".json")):
                full = os.path.join(dirpath, fname)
                rel  = os.path.relpath(full, ROOT)
                nova_files[rel] = open(full, "rb").read()

    # Build FAT32 image
    print(f"  Building {size_mb}MB FAT32 image...")
    fat = FAT32Builder(size_mb=size_mb)
    fat.add_file("EFI\\BOOT\\BOOTX64.EFI", efi_data)
    for rel, data in nova_files.items():
        fat_path = "NOVA\\" + rel.replace("/", "\\").replace("..", "__")
        fat.add_file(fat_path, data)

    img_data = fat.build()
    with open(IMG_PATH, "wb") as f:
        f.write(img_data)
    print(f"  Image: {IMG_PATH} ({os.path.getsize(IMG_PATH)//1024//1024} MB)")
    return IMG_PATH


def launch_qemu(img_path: str, ovmf_path: str, memory_mb: int = 512,
                gui: bool = True):
    """Launch QEMU with UEFI firmware booting our image."""
    qemu = find_qemu()
    if not qemu:
        print("  QEMU not found. Install it:")
        print("    Linux  : sudo apt install qemu-system-x86")
        print("    macOS  : brew install qemu")
        print("    Windows: https://www.qemu.org/download/")
        sys.exit(1)

    cmd = [
        qemu,
        "-m",       str(memory_mb),
        "-drive",   f"if=pflash,format=raw,readonly=on,file={ovmf_path}",
        "-drive",   f"format=raw,file={img_path}",
        "-net",     "none",
    ]
    if not gui:
        cmd += ["-nographic", "-serial", "stdio"]
    else:
        cmd += ["-vga", "std"]

    print(f"\n  Launching QEMU...")
    print(f"  Command: {' '.join(cmd)}\n")
    print("  " + "─" * 60)
    subprocess.run(cmd)


def install_deps():
    """Help the user install QEMU and OVMF."""
    print("  Installing dependencies...\n")
    import platform
    sys_  = platform.system()
    if sys_ == "Linux":
        pkg = "qemu-system-x86 ovmf"
        print(f"  Run: sudo apt install {pkg}")
        print(f"  Or:  sudo dnf install qemu-system-x86_64 edk2-ovmf")
        print(f"  Or:  sudo pacman -S qemu ovmf")
    elif sys_ == "Darwin":
        print("  Run: brew install qemu")
        print("  OVMF is bundled with QEMU on macOS (homebrew)")
    else:
        print("  Windows: download QEMU from https://qemu.org/download/")
        print("  OVMF:    download from https://github.com/tianocore/edk2")


