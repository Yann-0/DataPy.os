    args = ap.parse_args()

    if args.install:
        install_deps()
        sys.exit(0)

    print("\n  PyOS NOVA — VM Runner")
    print("  ─────────────────────────────────────────────────────────")
    print("  Boot chain: QEMU → OVMF (UEFI) → BOOTX64.EFI → Python")
    print("  No Linux kernel. No Syslinux. No Alpine. Just UEFI + Python.\n")

    img = build_image(args.img)

    if args.build_only:
        print(f"\n  Image ready: {img}")
        print(f"  Flash to USB: sudo dd if={img} of=/dev/sdX bs=4M status=progress")
        sys.exit(0)

    # Find or download OVMF
    ovmf = find_ovmf()
    if not ovmf:
        print("  OVMF firmware not found locally.")
        ans = input("  Download OVMF (~3MB)? [Y/n] ").strip().lower()
        if ans in ("", "y", "yes"):
            ovmf = download_ovmf()
        else:
            print("  Install OVMF manually (see --install) or run on real UEFI hardware.")
            sys.exit(1)

    print(f"  OVMF: {ovmf}")
    launch_qemu(img, ovmf, memory_mb=args.ram, gui=not args.nographic)
