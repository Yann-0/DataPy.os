"""
PyOS NOVA — VM Runner
======================
Boots PyOS NOVA in a QEMU virtual machine using UEFI firmware (OVMF).
No Linux kernel. No Syslinux. No bootloader software.

The boot chain:
  QEMU (hardware emulator)
    → OVMF firmware (UEFI, open-source, Apache-2.0 license)
    → EFI/BOOT/BOOTX64.EFI  ← generated by efi_builder.py
    → Python
    → NOVA kernel + shell

OVMF replaces the physical UEFI chip present in real hardware.
This lets you test NOVA on any machine before flashing to USB.

Usage:
  python3 nova_vm.py              # auto-build EFI + launch VM
  python3 nova_vm.py --install    # install QEMU + OVMF via pip helper
  python3 nova_vm.py --img SIZE   # create disk image of SIZE MB (default 512)
"""

