    ap.add_argument("--ram",      type=int, default=512,   metavar="MB",  help="VM RAM in MB")
    ap.add_argument("--nographic", action="store_true",                    help="Text-only mode")
    ap.add_argument("--install",   action="store_true",                    help="Show installation instructions")
